import { formatCurrency } from '../../../utils/number'
import { Report } from '../../../services/report/report.types'

interface Props {
  report: Report
}

const formatDate = (iso: string) =>
  new Date(iso).toLocaleString('en-PH', {
    dateStyle: 'medium',
    timeStyle: 'short',
  })

export const ReportDisplay = ({ report }: Props) => {
  return (
    <div className="flex flex-col gap-6 rounded-lg border bg-white p-6">
      <div className="flex flex-col gap-1">
        <p className="text-sm text-slate-500">
          Generated by{' '}
          <span className="font-medium text-slate-800">{report.createdBy.username}</span>{' '}
          on {formatDate(report.createdAt)}
        </p>
        <p className="text-sm text-slate-500">
          Period: {formatDate(report.fromDate)} — {formatDate(report.toDate)}
        </p>
      </div>

      <div className="grid grid-cols-3 gap-4">
        <div className="flex flex-col gap-1 rounded-lg border bg-slate-50 p-4">
          <span className="text-xs font-medium text-slate-500">Cash</span>
          <span className="text-xl font-bold text-slate-900">
            {formatCurrency(report.totalCash)}
          </span>
        </div>
        <div className="flex flex-col gap-1 rounded-lg border bg-slate-50 p-4">
          <span className="text-xs font-medium text-slate-500">GCash</span>
          <span className="text-xl font-bold text-slate-900">
            {formatCurrency(report.totalGCash)}
          </span>
        </div>
        <div className="flex flex-col gap-1 rounded-lg border bg-blue-50 p-4">
          <span className="text-xs font-medium text-blue-600">Total Income</span>
          <span className="text-xl font-bold text-blue-700">
            {formatCurrency(report.totalIncome)}
          </span>
        </div>
      </div>

      <div className="flex flex-col gap-3">
        <h3 className="text-sm font-semibold text-slate-700">Products Sold</h3>
        {report.products.length === 0 ? (
          <p className="py-4 text-center text-sm text-slate-400">
            No transactions found in this date range.
          </p>
        ) : (
          <div className="overflow-x-auto rounded-lg border">
            <table className="w-full text-sm">
              <thead className="bg-slate-50">
                <tr>
                  <th className="px-4 py-3 text-left font-medium text-slate-600">Product</th>
                  <th className="px-4 py-3 text-right font-medium text-slate-600">Qty Sold</th>
                  <th className="px-4 py-3 text-right font-medium text-slate-600">Price / Unit</th>
                  <th className="px-4 py-3 text-right font-medium text-slate-600">Total</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100">
                {report.products.map((p) => (
                  <tr key={p.productId}>
                    <td className="px-4 py-3 text-slate-800">{p.name}</td>
                    <td className="px-4 py-3 text-right text-slate-700">{p.quantitySold}</td>
                    <td className="px-4 py-3 text-right text-slate-700">
                      {formatCurrency(p.pricePerUnit)}
                    </td>
                    <td className="px-4 py-3 text-right font-semibold text-slate-900">
                      {formatCurrency(p.total)}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  )
}
